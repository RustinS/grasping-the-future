"""Records around a canonical export: the transaction marker, completeness check, declared window children."""

import json
import os
import re
import tempfile
import time
import numpy as np
from pathlib import Path
from gtf.utils import rprint as print
from gtf.utils.canonical import validate_canonical_npz
from gtf.utils.video_timing import FRAME_TIME_CONVENTION, array_sha256, file_sha256, validate_exact_timing_arrays


CANONICAL_TRANSACTION_FORMAT = "action100m-canonical-transaction-v4"
CANONICAL_TRANSACTION_MARKER = ".canonical_done.json"
INTERACTION_WINDOW_CHILDREN_FIELD = "interaction_window_children"
RETIRED_INTERACTION_WINDOWS_DIR = "results_retired_interaction_windows"


def _write_json_atomic(path, payload):
    """Publish JSON only after the complete payload is durable."""

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.tmp-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            json.dump(payload, stream, indent=2)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def _validated_interaction_window_children(segment_name, value):
    """Return a transaction's exact, ordered derived-child roster or ``None``.

    Child names are generated by this exporter, so accepting arbitrary paths or
    sparse/duplicate indices would turn a metadata field into a second source of
    truth.  Requiring the canonical ``parent__iw1..N`` order keeps the roster
    deterministic and safe to resolve next to the parent directory.
    """

    if not isinstance(value, list) or any(not isinstance(name, str) for name in value):
        return None
    expected = [f"{segment_name}__iw{index}" for index in range(1, len(value) + 1)]
    return list(value) if value == expected else None


def _existing_interaction_window_children(segment_dir):
    """List exact generated child directories; ignore similarly named sources."""

    segment_dir = Path(segment_dir)
    pattern = re.compile(rf"^{re.escape(segment_dir.name)}__iw[1-9][0-9]*$")
    try:
        siblings = segment_dir.parent.iterdir()
    except OSError:
        return []
    return sorted(entry.name for entry in siblings if pattern.fullmatch(entry.name) and entry.is_dir())


def declared_interaction_window_children(segment_dir, expected_segment=None):
    """Read a committed parent's declared derived-child roster.

    Downstream stages use this lightweight reader instead of globbing ``__iw*``
    directories, which may be left over from earlier exports. Full artifact
    validation is done by :func:`outputs_complete`.
    """

    segment_dir = Path(segment_dir)
    expected = expected_segment or segment_dir.name
    metadata_path = segment_dir / "canonical" / "metadata.json"
    marker_path = segment_dir / "canonical" / CANONICAL_TRANSACTION_MARKER
    try:
        metadata = json.loads(metadata_path.read_text())
        marker = json.loads(marker_path.read_text())
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"canonical child roster is uncommitted for {expected}") from exc
    if not isinstance(metadata, dict) or not isinstance(marker, dict):
        raise ValueError(f"canonical child roster is malformed for {expected}")
    metadata_children = _validated_interaction_window_children(expected, metadata.get(INTERACTION_WINDOW_CHILDREN_FIELD))
    marker_children = _validated_interaction_window_children(expected, marker.get(INTERACTION_WINDOW_CHILDREN_FIELD))
    if (
        metadata.get("canonical_transaction_format") != CANONICAL_TRANSACTION_FORMAT
        or marker.get("format") != CANONICAL_TRANSACTION_FORMAT
        or marker.get("segment_id") != expected
        or marker.get("metadata_sha256") != _file_sha256(metadata_path)
        or metadata_children is None
        or marker_children != metadata_children
    ):
        raise ValueError(f"canonical child roster is stale or malformed for {expected}")
    actual_children = _existing_interaction_window_children(segment_dir)
    if actual_children != sorted(metadata_children):
        raise ValueError(f"canonical child roster disagrees with disk for {expected}")
    return metadata_children


def _retire_unexpected_interaction_window_children(segment_dir, expected_children):
    """Atomically quarantine stale generated children instead of deleting them."""

    segment_dir = Path(segment_dir)
    expected = set(expected_children)
    stale = [name for name in _existing_interaction_window_children(segment_dir) if name not in expected]
    if not stale:
        return []
    retirement_root = segment_dir.parent / RETIRED_INTERACTION_WINDOWS_DIR / segment_dir.name
    retirement_root.mkdir(parents=True, exist_ok=True)
    retired = []
    for name in stale:
        source = segment_dir.parent / name
        while True:
            destination = retirement_root / f"{name}.{time.time_ns()}.{os.getpid()}"
            if not destination.exists():
                break
        os.replace(source, destination)
        retired.append((source, destination))
        print(f"  Retired stale window child {source.name} -> {destination}")
    return retired


def outputs_complete(segment_dir, expected_segment=None, _seen=None):
    """Validate the canonical transaction before resume skips the producer.

    Checks the transaction marker against the canonical, its metadata, the video, the optimized input and the frame
    roster, and recurses into the declared ``__iwN`` children. An interrupted or stale export is not complete.
    """

    segment_dir = Path(segment_dir)
    canonical_path = segment_dir / "canonical" / "canonical.npz"
    metadata_path = segment_dir / "canonical" / "metadata.json"
    valid, _errors = validate_canonical_npz(canonical_path)
    if not valid or not metadata_path.is_file():
        return False
    try:
        metadata = json.loads(metadata_path.read_text())
    except (OSError, json.JSONDecodeError):
        return False
    if not isinstance(metadata, dict):
        return False
    expected = expected_segment or segment_dir.name
    seen = set() if _seen is None else _seen
    resolved_segment = segment_dir.resolve()
    if resolved_segment in seen:
        return False
    seen.add(resolved_segment)
    if metadata.get("segment_id") != expected:
        return False
    marker_path = canonical_path.parent / CANONICAL_TRANSACTION_MARKER
    transaction_format = metadata.get("canonical_transaction_format")
    if transaction_format == CANONICAL_TRANSACTION_FORMAT:
        try:
            marker = json.loads(marker_path.read_text())
            with np.load(canonical_path, allow_pickle=False) as archive:
                indices, times = validate_exact_timing_arrays(
                    archive["frame_indices"],
                    archive["frame_times_s"],
                    archive["frame_time_convention"],
                )
        except (KeyError, OSError, RuntimeError, ValueError, json.JSONDecodeError):
            return False
        video_path = segment_dir / "video.mp4"
        opt_subdir = metadata.get("optimized_subdir")
        if opt_subdir not in {"optimized_mano", "optimized_stage2"}:
            return False
        optimized_path = segment_dir / opt_subdir / "optimized.npz"
        if not video_path.is_file() or not optimized_path.is_file():
            return False
        video_sha = file_sha256(video_path)
        optimized_sha = _file_sha256(optimized_path)
        frame_roster_sha = array_sha256(indices, "<i8")
        frame_times_sha = array_sha256(times, "<f8")
        metadata_children = _validated_interaction_window_children(expected, metadata.get(INTERACTION_WINDOW_CHILDREN_FIELD))
        marker_children = _validated_interaction_window_children(expected, marker.get(INTERACTION_WINDOW_CHILDREN_FIELD))
        base_complete = (
            isinstance(marker, dict)
            and marker.get("format") == CANONICAL_TRANSACTION_FORMAT
            and marker.get("segment_id") == expected
            and marker.get("canonical_sha256") == _file_sha256(canonical_path)
            and marker.get("metadata_sha256") == _file_sha256(metadata_path)
            and marker.get("video_sha256") == video_sha
            and marker.get("optimized_subdir") == opt_subdir
            and marker.get("optimized_sha256") == optimized_sha
            and marker.get("frame_roster_sha256") == frame_roster_sha
            and marker.get("frame_times_sha256") == frame_times_sha
            and metadata.get("frame_time_convention") == FRAME_TIME_CONVENTION
            and metadata.get("video_sha256") == video_sha
            and metadata.get("optimized_sha256") == optimized_sha
            and metadata.get("selected_frame_times_sha256") == frame_times_sha
            and metadata_children is not None
            and marker_children == metadata_children
            and _existing_interaction_window_children(segment_dir) == sorted(metadata_children)
        )
        if not base_complete:
            return False
        return all(
            outputs_complete(
                segment_dir.parent / child,
                expected_segment=child,
                _seen=seen,
            )
            for child in metadata_children
        )
    # Any other transaction format must be re-exported.
    return False


def _json_safe(value):
    """Return deterministic strict-JSON provenance without changing numeric outputs."""
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    if isinstance(value, np.ndarray):
        return _json_safe(value.tolist())
    if isinstance(value, (np.bool_,)):
        return bool(value)
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        scalar = float(value)
        return scalar if np.isfinite(scalar) else None
    if isinstance(value, (str, bool, int)) or value is None:
        return value
    raise TypeError(f"object-refine provenance is not JSON-safe: {type(value).__name__}")


def _file_sha256(path):
    path = Path(path)
    if not path.is_file():
        raise ValueError(f"required artifact is not a file: {path}")
    return file_sha256(path)
